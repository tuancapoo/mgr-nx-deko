#!/usr/bin/env python3
"""Direct3D census for Metal Gear Rising: how often each function of the Direct3D range runs per presented frame.

MGR has no reference game with named XDK functions on this machine, so tools/d3d_match.py cannot name its Direct3D.
This finds them by behaviour instead: every function in the range gets a counting hook, D3DDevice_Swap (the only
caller of VdSwap, sub_826B3510) counts frames, and every 300 frames the log lists the busiest functions with their
calls per frame. A draw function runs about as often per frame as the emulated GPU's draw_calls counter says
(title screen: median 534).

  python tools/mgr_d3d_census.py [--lo 0x82690000] [--hi 0x826D0000]
      writes app/mgr_src/mgr_d3d_census.cpp (diagnostic only, not part of a normal build)
  cmake -S app -B out/pc -DMGR_D3D_CENSUS=ON   then build, and run the game: lines "[d3d census]" in the log
  cmake -S app -B out/pc -DMGR_D3D_CENSUS=OFF  back to the normal build

The range 0x82690000-0x826D0000 comes from the generated code (MGR-PORT-PLAN.md): the DRAW_INDX_2 packet builders
(sub_826AA740, ...), D3DDevice_Swap (sub_826B3510) and the GPU interrupt callback (0x826B3FE0) sit in it. It may also
hold other libraries (SA2's "Direct3D range" started with XAPI's heap functions), which is fine for a census.
"""
import argparse
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN = os.path.join(ROOT, 'app', 'generated', 'default')
OUT = os.path.join(ROOT, 'app', 'mgr_src', 'mgr_d3d_census.cpp')
SWAP = 0x826B3510
DEF = re.compile(r'^DEFINE_REX_FUNC\(sub_([0-9A-F]{8})\)')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--lo', default='0x82690000')
    ap.add_argument('--hi', default='0x826D0000')
    a = ap.parse_args()
    lo, hi = int(a.lo, 16), int(a.hi, 16)
    funcs = set()
    for path in glob.glob(os.path.join(GEN, 'sa2_recomp.*.cpp')):
        for line in open(path, encoding='utf-8', errors='ignore'):
            m = DEF.match(line)
            if m and lo <= int(m.group(1), 16) < hi:
                funcs.add(int(m.group(1), 16))
    funcs = sorted(funcs)
    with open(OUT, 'w', newline='\n') as o:
        o.write('// Generated by tools/mgr_d3d_census.py: the Direct3D census build (diagnostic only; MGR_D3D_CENSUS=ON).\n')
        o.write('#include <algorithm>\n#include <atomic>\n#include <cstdint>\n#include <cstdio>\n#include <vector>\n\n')
        o.write('#include <rex/hook.h>\n#include <rex/logging.h>\n#include <rex/ppc.h>\n\n')
        o.write('namespace {\n')
        o.write(f'constexpr uint32_t kAddr[{len(funcs)}] = {{\n')
        for i in range(0, len(funcs), 8):
            o.write('    ' + ', '.join(f'0x{f:08X}u' for f in funcs[i:i + 8]) + ',\n')
        o.write('};\n')
        o.write(f'std::atomic<uint64_t> g_calls[{len(funcs)}];\n')
        o.write('std::atomic<uint64_t> g_frames{0};\n')
        o.write(f'uint64_t g_last[{len(funcs)}];\n')
        o.write('''uint64_t g_last_frames = 0;
uint32_t g_window = 0;

// Per window of 300 frames: calls per frame of every function that ran in it, the top 40 to the log and all of them
// to d3d_census.csv next to the executable (window, frames, address, calls per frame).
void Report() {
  const uint64_t frames = g_frames.load(std::memory_order_relaxed);
  const uint64_t span = frames - g_last_frames;
  g_last_frames = frames;
  std::vector<std::pair<uint64_t, uint32_t>> rows;
  for (uint32_t i = 0; i < std::size(kAddr); ++i) {
    const uint64_t n = g_calls[i].load(std::memory_order_relaxed);
    if (n != g_last[i]) rows.emplace_back(n - g_last[i], kAddr[i]);
    g_last[i] = n;
  }
  std::sort(rows.rbegin(), rows.rend());
  ++g_window;
  REXLOG_INFO("[d3d census] window {} (frames {}-{}): {} functions ran; busiest (calls per frame):", g_window,
              frames - span, frames, rows.size());
  for (size_t i = 0; i < rows.size() && i < 40; ++i) {
    REXLOG_INFO("[d3d census]   sub_{:08X}  {:.1f}/frame", rows[i].second, double(rows[i].first) / double(span));
  }
  if (std::FILE* f = std::fopen("d3d_census.csv", g_window == 1 ? "w" : "a")) {
    if (g_window == 1) std::fputs("window,frames,address,calls_per_frame\\n", f);
    for (const auto& r : rows) {
      std::fprintf(f, "%u,%llu,%08X,%.2f\\n", g_window, static_cast<unsigned long long>(span), r.second,
                   double(r.first) / double(span));
    }
    std::fclose(f);
  }
}
}  // namespace

''')
        for i, f in enumerate(funcs):
            o.write(f'REX_EXTERN(__imp__sub_{f:08X});\n')
            if f == SWAP:
                o.write(f'REX_HOOK_RAW(sub_{f:08X}) {{\n'
                        f'  g_calls[{i}].fetch_add(1, std::memory_order_relaxed);\n'
                        f'  __imp__sub_{f:08X}(ctx, base);\n'
                        f'  if (g_frames.fetch_add(1, std::memory_order_relaxed) % 300 == 299) Report();\n'
                        f'}}\n')
            else:
                o.write(f'REX_HOOK_RAW(sub_{f:08X}) {{ g_calls[{i}].fetch_add(1, std::memory_order_relaxed); '
                        f'__imp__sub_{f:08X}(ctx, base); }}\n')
    print(f'{len(funcs)} functions in {lo:08X}-{hi:08X}; wrote {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    main()
